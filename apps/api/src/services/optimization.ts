import { analyzeInternalLinks, buildInlinks, scorePriority } from '@phoenixx/seo-engine';
import { AppError, normalizeUrl, type RecommendationType } from '@phoenixx/shared';
import type { AppContext } from '../context.js';
import { getProject, latestCrawledPages, profileOf } from './common.js';
import { fingerprint, upsertRecommendation } from './recommendations.js';
import { pageSearchStats } from './crawl.js';
import { profileSummary } from './content.js';

/** Internal Linking Agent (workflow 6): crawl graph → topical similarity → suggestions → (AI anchors) → recommendations. */
export async function runInternalLinks(ctx: AppContext, projectId: string, input: { useAi?: boolean; correlationId?: string } = {}) {
  const profile = profileOf(await getProject(ctx, projectId));
  const { pages } = await latestCrawledPages(ctx, projectId);
  if (!pages.length) throw new AppError('Run a crawl first', 400, 'no_crawl');
  const inlinks = buildInlinks(pages);
  const { byPage } = await pageSearchStats(ctx, projectId);
  const { stats, suggestions } = analyzeInternalLinks(pages, inlinks, profile, { pageImpressions: new Map([...byPage.entries()].map(([u, s]) => [u, s.impressions])) });
  let refined = suggestions;
  let aiUsed = false;
  if ((input.useAi ?? true) && ctx.ai.enabled && suggestions.length) {
    try {
      const top = suggestions.slice(0, 25);
      const r = await ctx.ai.run('internal-linking', { pages: pages.filter((p) => p.indexable).map((p) => ({ url: p.url, title: p.title, h1: p.h1s[0] ?? null })), suggestions: top }, { projectId, correlationId: input.correlationId });
      const byKey = new Map(r.data.items.map((i) => [`${i.sourceUrl}|${i.targetUrl}`, i]));
      refined = suggestions.map((s) => {
        const a = byKey.get(`${s.sourceUrl}|${s.targetUrl}`);
        return a ? { ...s, anchorText: a.anchorText, reason: `${s.reason}. Placement: ${a.placement}`, keep: a.keep } : s;
      }) as typeof suggestions;
      aiUsed = true;
    } catch (e) {
      ctx.log.warn('links.ai_failed', { error: (e as Error).message });
    }
  }
  let recs = 0;
  for (const s of refined) {
    if ((s as { keep?: boolean }).keep === false) continue;
    await ctx.db.query(
      `INSERT INTO internal_link_opportunities(project_id, source_url, target_url, anchor_text, reason, priority, score, similarity) VALUES ($1,$2,$3,$4,$5,$6,$7,$8)
       ON CONFLICT (project_id, source_url, target_url) DO UPDATE SET anchor_text = EXCLUDED.anchor_text, reason = EXCLUDED.reason, priority = EXCLUDED.priority, score = EXCLUDED.score, similarity = EXCLUDED.similarity`,
      [projectId, s.sourceUrl, s.targetUrl, s.anchorText, s.reason, s.priority, s.score, s.similarity],
    );
    if (s.priority !== 'low') {
      const pr = scorePriority({ impact: 2.5, effort: 1, businessRelevance: 3.5, confidence: 0.6, notes: [s.reason] });
      const rec = await upsertRecommendation(ctx, {
        projectId,
        source: 'internal_linking',
        type: 'internal_link',
        pageUrl: s.sourceUrl,
        title: `Link ${new URL(s.sourceUrl).pathname} → ${new URL(s.targetUrl).pathname}`,
        what: `Add a contextual link on ${new URL(s.sourceUrl).pathname} to ${new URL(s.targetUrl).pathname} using anchor text "${s.anchorText}".`,
        why: s.reason,
        evidence: [{ label: 'Similarity', value: s.similarity }, { label: 'Score', value: s.score }],
        currentValue: null,
        proposedValue: `<a href="${new URL(s.targetUrl).pathname}">${s.anchorText}</a>`,
        expectedPurpose: 'Connect related topics for users and pass internal link equity.',
        risk: 'low',
        priority: { ...pr, priority: s.priority === 'high' ? 'high' : 'medium' },
        aiGenerated: aiUsed,
        fingerprint: fingerprint('link', projectId, s.sourceUrl, s.targetUrl),
        queueForApproval: false,
      });
      await ctx.db.query(`UPDATE internal_link_opportunities SET recommendation_id = $2, status = 'recommended' WHERE project_id = $1 AND source_url = $3 AND target_url = $4`, [projectId, rec.id, s.sourceUrl, s.targetUrl]);
      recs++;
    }
  }
  return { pages: stats.length, orphans: stats.filter((s) => s.orphan).length, suggestions: refined.length, recommendations: recs, aiUsed, stats };
}

const FIELD_TO_TYPE: Record<string, RecommendationType> = { title: 'title', meta_description: 'meta_description', h1: 'h1', headings: 'headings', content: 'content', faq: 'faq', internal_link: 'internal_link', alt_text: 'alt_text', schema: 'schema', cta: 'cta' };

/** On-Page Optimization (workflow 5): page → current SEO state → AI recommendations → approval queue. */
export async function runOnPageOptimization(ctx: AppContext, projectId: string, input: { pageUrl: string; correlationId?: string }) {
  if (!ctx.ai.enabled) throw new AppError('On-page AI optimisation requires an AI provider. Rule-based recommendations are still generated by each crawl.', 400, 'ai_disabled');
  const url = normalizeUrl(input.pageUrl);
  if (!url) throw new AppError('Invalid pageUrl', 400, 'validation');
  const profile = profileOf(await getProject(ctx, projectId));
  const { pages } = await latestCrawledPages(ctx, projectId);
  const page = pages.find((p) => p.url === url || p.finalUrl === url);
  if (!page) throw new AppError('Page not found in the latest crawl', 404, 'not_found');
  const pageRow = await ctx.db.one<{ id: string; inlinks: number }>(`SELECT p.id, p.inlinks FROM pages p JOIN websites w ON w.id = p.website_id WHERE w.project_id = $1 AND p.url = $2`, [projectId, page.url]);
  const issues = await ctx.db.query<{ rule_id: string; title: string }>(`SELECT rule_id, title FROM seo_issues WHERE project_id = $1 AND url = $2 AND status = 'open'`, [projectId, page.url]);
  const queries = await ctx.db.query(
    `SELECT query, SUM(impressions)::int AS impressions, SUM(clicks)::int AS clicks, ROUND((SUM(clicks)::numeric/NULLIF(SUM(impressions),0))*100,2)::float AS ctr_pct, ROUND((SUM(position*impressions)/NULLIF(SUM(impressions),0))::numeric,1)::float AS position
     FROM search_console_data WHERE project_id = $1 AND page = $2 AND query <> '' GROUP BY query ORDER BY impressions DESC LIMIT 20`,
    [projectId, page.url],
  );
  const r = await ctx.ai.run(
    'onpage-optimization',
    {
      profile: profileSummary(profile),
      page: { url: page.url, title: page.title, metaDescription: page.metaDescription, h1s: page.h1s, h2s: page.h2s, wordCount: page.wordCount, imagesWithoutAlt: page.images.filter((i) => !i.hasAlt).map((i) => i.src).slice(0, 10), inlinks: pageRow?.inlinks ?? 0, outlinks: page.internalLinks.map((l) => l.href).slice(0, 30), schemaTypes: page.structuredData.flatMap((s) => s.types), issues },
      content: page.textSample,
      queries,
      sitePages: pages.filter((p) => p.indexable && p.url !== page.url).map((p) => ({ url: p.url, title: p.title })),
    },
    { projectId, correlationId: input.correlationId },
  );
  let created = 0;
  for (const rec of r.data.recommendations) {
    const type = FIELD_TO_TYPE[rec.field] ?? 'other';
    const pr = scorePriority({ impact: ['title', 'meta_description', 'h1', 'content'].includes(rec.field) ? 3.5 : 2, effort: rec.field === 'content' ? 3 : 1, impressions: (queries as any[]).reduce((s, q) => s + q.impressions, 0), businessRelevance: 4, confidence: 0.6 });
    await upsertRecommendation(ctx, {
      projectId,
      source: 'ai',
      type,
      pageUrl: page.url,
      pageId: pageRow?.id,
      title: `${rec.field.replace('_', ' ')}: ${new URL(page.url).pathname}`,
      what: rec.recommended.slice(0, 500),
      why: rec.reason,
      evidence: [{ label: 'Top queries', value: (queries as any[]).slice(0, 3).map((q) => q.query).join(', ') || 'none' }, { label: 'Model', value: r.model }],
      currentValue: rec.current,
      proposedValue: rec.recommended,
      expectedPurpose: rec.expectedPurpose,
      risk: rec.risk,
      priority: pr,
      aiGenerated: true,
      aiModel: r.model,
      fingerprint: fingerprint('onpage', projectId, page.url, rec.field, rec.recommended.slice(0, 80)),
      queueForApproval: true,
    });
    created++;
  }
  return { page: page.url, recommendations: created, faqs: r.data.faqs, model: r.model, cached: r.cached };
}
